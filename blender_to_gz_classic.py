import bpy
import os
from bpy_extras.io_utils import ImportHelper
from bpy.types import Operator
import xml.etree.ElementTree as ET
from xml.dom import minidom


############################################################
# Export SDF model + config + world file from Blender
# Target: Blender 3.x+
############################################################

def export_sdf(prefix_path):

    # -----------------------------
    # Settings
    # -----------------------------
    dae_filename = 'floor_with_electronics.dae'
    sdf_filename = 'floor_with_electronics.sdf'
    model_config_filename = 'floor_with_electronics.config'
    world_filename = 'floor_with_electronics.world'
    model_name = 'floor_with_electronics'
    meshes_folder = 'meshes'

    meshes_dir = os.path.join(prefix_path, meshes_folder)
    os.makedirs(meshes_dir, exist_ok=True)

    # -----------------------------
    # Collect objects
    # -----------------------------
    objects = bpy.context.scene.objects
    mesh_objects = [o for o in objects if o.type == 'MESH']

    # -----------------------------
    # Export COLLADA (.dae)
    # -----------------------------
    bpy.ops.object.select_all(action='DESELECT')

    for obj in mesh_objects:
        obj.select_set(True)

    if mesh_objects:
        bpy.context.view_layer.objects.active = mesh_objects[0]
        bpy.ops.wm.collada_export(
            filepath=os.path.join(meshes_dir, dae_filename),
            check_existing=False
        )

    # -----------------------------
    # Generate model.sdf
    # -----------------------------
    sdf = ET.Element('sdf', attrib={'version': '1.7'})
    model = ET.SubElement(sdf, 'model', attrib={'name': model_name})

    static = ET.SubElement(model, 'static')
    static.text = "true"

    for obj in mesh_objects:

        link = ET.SubElement(model, 'link', attrib={'name': f"{obj.name}_link"})

        # VISUAL
        visual = ET.SubElement(link, 'visual', attrib={'name': obj.name})
        geometry = ET.SubElement(visual, 'geometry')
        mesh = ET.SubElement(geometry, 'mesh')

        uri = ET.SubElement(mesh, 'uri')
        uri.text = f"{meshes_folder}/{dae_filename}"

        submesh = ET.SubElement(mesh, 'submesh')
        submesh_name = ET.SubElement(submesh, 'name')
        submesh_name.text = obj.name

        # COLLISION
        collision = ET.SubElement(link, 'collision', attrib={'name': f"{obj.name}_collision"})
        geometry_c = ET.SubElement(collision, 'geometry')
        mesh_c = ET.SubElement(geometry_c, 'mesh')
        uri_c = ET.SubElement(mesh_c, 'uri')
        uri_c.text = f"{meshes_folder}/{dae_filename}"

    # Write model.sdf
    xml_string = ET.tostring(sdf, encoding='unicode')
    pretty_xml = minidom.parseString(xml_string).toprettyxml(indent="  ")

    with open(os.path.join(prefix_path, sdf_filename), "w") as f:
        f.write(pretty_xml)

    # -----------------------------
    # Generate model.config
    # -----------------------------
    model_config = ET.Element('model')

    name = ET.SubElement(model_config, 'name')
    name.text = model_name

    version = ET.SubElement(model_config, 'version')
    version.text = "1.0"

    sdf_tag = ET.SubElement(model_config, 'sdf', attrib={'version': '1.7'})
    sdf_tag.text = sdf_filename

    author = ET.SubElement(model_config, 'author')
    author_name = ET.SubElement(author, 'name')
    author_name.text = "Generated by Blender SDF Exporter"

    description = ET.SubElement(model_config, 'description')
    description.text = "Auto-generated model from Blender."

    xml_string = ET.tostring(model_config, encoding='unicode')
    pretty_xml = minidom.parseString(xml_string).toprettyxml(indent="  ")

    with open(os.path.join(prefix_path, model_config_filename), "w") as f:
        f.write(pretty_xml)

    # -----------------------------
    # Generate world file
    # -----------------------------
    sdf_world = ET.Element('sdf', attrib={'version': '1.7'})
    world = ET.SubElement(sdf_world, 'world', attrib={'name': 'default'})

    gravity = ET.SubElement(world, 'gravity')
    gravity.text = "0 0 -9.8"

    magnetic_field = ET.SubElement(world, 'magnetic_field')
    magnetic_field.text = "6e-06 2.3e-05 -4.2e-05"

    atmosphere = ET.SubElement(world, 'atmosphere', attrib={'type': 'adiabatic'})

    physics = ET.SubElement(world, 'physics', attrib={'type': 'ode'})
    ET.SubElement(physics, 'max_step_size').text = "0.01"
    ET.SubElement(physics, 'real_time_factor').text = "1"
    ET.SubElement(physics, 'real_time_update_rate').text = "100"

    scene = ET.SubElement(world, 'scene')
    ET.SubElement(scene, 'ambient').text = "1 1 1 1"
    ET.SubElement(scene, 'background').text = "0.53 0.81 0.92 1"
    ET.SubElement(scene, 'shadows').text = "0"

    # Light
    light = ET.SubElement(world, 'light', attrib={
        'name': 'directional_light',
        'type': 'directional'
    })

    ET.SubElement(light, 'pose').text = "3 1 2 0 0 0"
    ET.SubElement(light, 'cast_shadows').text = "false"
    ET.SubElement(light, 'intensity').text = "1"
    ET.SubElement(light, 'direction').text = "0 0 -1"
    ET.SubElement(light, 'diffuse').text = "0.8 0.8 0.8 1"
    ET.SubElement(light, 'specular').text = "0.2 0.2 0.2 1"

    # Include model
    include = ET.SubElement(world, 'include')
    ET.SubElement(include, 'uri').text = f"model://{model_name}"

    # Write world
    xml_string = ET.tostring(sdf_world, encoding='unicode')
    pretty_xml = minidom.parseString(xml_string).toprettyxml(indent="  ")

    with open(os.path.join(prefix_path, world_filename), "w") as f:
        f.write(pretty_xml)

    print("Export complete.")


############################################################
# UI Operator
############################################################

class OT_ExportSDF(Operator, ImportHelper):
    bl_idname = "export.sdf_world"
    bl_label = "Export SDF World"

    directory: bpy.props.StringProperty(name="Output Directory")

    def execute(self, context):
        if not os.path.isdir(self.directory):
            print("Invalid directory")
        else:
            export_sdf(self.directory)
        return {'FINISHED'}


def register():
    bpy.utils.register_class(OT_ExportSDF)


def unregister():
    bpy.utils.unregister_class(OT_ExportSDF)


if __name__ == "__main__":
    register()
    bpy.ops.export.sdf_world('INVOKE_DEFAULT')